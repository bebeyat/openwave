#!/usr/bin/env node
// Generates the Rust-dependency section of THIRD_PARTY_NOTICES.md from `cargo metadata --locked`
// (Windows target, normal dependency edges only: dev- and build-only crates are not shipped).
//
//   node scripts/gen-notices.mjs            # rewrite THIRD_PARTY_NOTICES.md and print a license summary
//   node scripts/gen-notices.mjs --check    # fail if a non-permissive license shows up
//
// The hand-written parts of THIRD_PARTY_NOTICES.md (fonts, icons, yt-dlp ...) live in
// scripts/notices-header.md; this script concatenates header + generated section into THIRD_PARTY_NOTICES.md.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = process.env.NOTICES_TARGET ?? "x86_64-pc-windows-msvc";
const BANNED = /\b(A?GPL|LGPL|SSPL|BUSL|CC-BY-NC|Commons-Clause)/i;

const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--locked", "--format-version", "1", "--filter-platform", TARGET], {
    cwd: root, maxBuffer: 1 << 29, encoding: "utf8",
  }),
);
const byId = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));

// Reachability over normal (kind === null) edges from the root package.
const linked = new Set();
const stack = [meta.resolve.root];
while (stack.length) {
  const id = stack.pop();
  if (linked.has(id)) continue;
  linked.add(id);
  for (const d of nodes.get(id).deps) {
    if (d.dep_kinds.some((k) => k.kind === null)) stack.push(d.pkg);
  }
}
linked.delete(meta.resolve.root);

const pkgs = [...linked].map((id) => byId.get(id)).sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const LICENSE_FILE = /^(licen[sc]e|copying|unlicense)([-_.].*)?$/i;
const NOTICE_FILE = /^notice([-_.].*)?$/i;

const norm = (s) => s.replace(/\r\n/g, "\n").trim();
const groups = new Map(); // hash -> { text, crates:Set }
const notices = new Map(); // hash -> { text, crates:Set }
const noFile = [];
const spdxCount = new Map();

const COPY = /^\s*(copyright|\(c\))\b/i;
const PLACEHOLDER = /yyyy|\[name/i;
const bodyOf = (text) => norm(text).split("\n").filter((l) => !COPY.test(l)).join("\n").replace(/\s+/g, " ").trim();
const holdersOf = (text) => norm(text).split("\n").filter((l) => COPY.test(l) && !PLACEHOLDER.test(l)).map((l) => l.trim());
const add = (map, text, label) => {
  const h = createHash("sha256").update(bodyOf(text)).digest("hex");
  if (!map.has(h)) map.set(h, { text: norm(text), crates: new Map() });
  const g = map.get(h);
  if (!g.crates.has(label)) g.crates.set(label, new Set());
  for (const c of holdersOf(text)) g.crates.get(label).add(c);
};

for (const p of pkgs) {
  const label = `${p.name} ${p.version}`;
  const spdx = p.license ?? (p.license_file ? `see ${p.license_file}` : "UNKNOWN");
  spdxCount.set(spdx, (spdxCount.get(spdx) ?? 0) + 1);
  const dir = dirname(p.manifest_path);
  let found = 0;
  for (const f of readdirSync(dir)) {
    const full = join(dir, f);
    if (NOTICE_FILE.test(f)) add(notices, readFileSync(full, "utf8"), label);
    else if (LICENSE_FILE.test(f) && !readdirSync(dir, { withFileTypes: true }).find((e) => e.name === f)?.isDirectory()) {
      add(groups, readFileSync(full, "utf8"), label);
      found++;
    }
  }
  if (!found) noFile.push(`${label} (${spdx}) - authors: ${p.authors.join(", ") || "see repository"}`);
}

const bad = [...spdxCount.keys()].filter((s) => BANNED.test(s) || s === "UNKNOWN");
const lines = [];
lines.push(`Generated by \`node scripts/gen-notices.mjs\` from \`cargo metadata --locked --filter-platform ${TARGET}\`.`);
lines.push(`${pkgs.length} crates are linked through normal dependency edges (build-only and dev-only crates are not listed).`, "");
lines.push("### Crates", "", "| Crate | Version | License (SPDX) | Source |", "|---|---|---|---|");
for (const p of pkgs) {
  const src = p.repository ?? p.homepage ?? (p.source?.startsWith("registry") ? `https://crates.io/crates/${p.name}` : "");
  lines.push(`| ${p.name} | ${p.version} | ${(p.license ?? "see license file").replace(/\|/g, "/")} | ${src} |`);
}
lines.push("", "### License texts", "",
  "Each text below is reproduced exactly as shipped in the crate(s) listed under it. Where a crate is offered under",
  "`A OR B`, OpenWave elects the permissive terms of either option; all option texts that the crate ships are included.", "");
let i = 0;
for (const g of [...groups.values()].sort((a, b) => b.crates.size - a.crates.size)) {
  i += 1;
  const shown = g.text
    .split("\n")
    .map((l) => (COPY.test(l) && !PLACEHOLDER.test(l) ? "[Copyright line: see the per-crate list below]" : l))
    .filter((l, k, a) => !(l.startsWith("[Copyright line") && a[k - 1]?.startsWith("[Copyright line")))
    .join("\n");
  lines.push(`#### License text ${i}`, "", "```text", shown, "```", "", "Used by (with the copyright notice each crate ships):", "");
  for (const [c, hs] of [...g.crates].sort((a, b) => a[0].localeCompare(b[0]))) lines.push(`- ${c}${hs.size ? " - " + [...hs].join(" / ") : ""}`);
  lines.push("");
}
if (notices.size) {
  lines.push("### NOTICE files (Apache-2.0 section 4(d))", "");
  let n = 0;
  for (const g of notices.values()) {
    n += 1;
    lines.push(`#### Notice ${n}`, "", `From: ${[...g.crates.keys()].sort().join(", ")}`, "", "```text", g.text, "```", "");
  }
}
if (noFile.length) {
  lines.push("### Crates without a license file in their package", "",
    "These crates declare an SPDX expression in Cargo.toml but ship no separate license file in their package (typically because the license sits at the repository root). Their terms are the standard text of the SPDX identifier shown (MIT and Apache-2.0 texts appear above; BSL-1.0 is the Boost Software License reproduced above); the copyright holders are the authors named in each crate's repository.", "");
  for (const c of noFile) lines.push(`- ${c}`);
  lines.push("");
}

const section = lines.join("\n");
const headerPath = join(root, "scripts", "notices-header.md");
if (existsSync(headerPath)) writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), readFileSync(headerPath, "utf8").replace("{{INTER_OFL}}", () => norm(readFileSync(join(root, "licenses", "Inter-OFL-1.1.txt"), "utf8"))).replace("{{LUCIDE}}", () => norm(readFileSync(join(root, "licenses", "Lucide-ISC.txt"), "utf8"))).trimEnd() + "\n\n" + section.replace(/^### /gm, "### ").trimEnd() + "\n");

console.log(`linked crates: ${pkgs.length}`);
for (const [k, v] of [...spdxCount].sort((a, b) => b[1] - a[1])) console.log(String(v).padStart(4), k);
console.log("license text groups:", groups.size, "| notices:", notices.size, "| without file:", noFile.length);
if (bad.length) { console.error("NON-PERMISSIVE OR UNKNOWN LICENSES:", bad.join("; ")); if (process.argv.includes("--check")) process.exit(1); }
