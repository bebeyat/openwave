// Copies the bundled font files, Lucide SVGs, language flags and license texts out of node_modules.
// Run with `npm run assets` after editing icons.txt (build.rs picks icons up automatically).
import { copyFileSync, mkdirSync, readFileSync, writeFileSync, existsSync, readdirSync, unlinkSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const nm = join(here, "node_modules");

const fontDir = join(root, "assets", "fonts");
const iconDir = join(root, "assets", "icons");
const licDir = join(root, "licenses");
for (const d of [fontDir, iconDir, licDir]) mkdirSync(d, { recursive: true });

// Fonts: Latin + Latin Extended covers Turkish and English.
for (const subset of ["latin", "latin-ext"]) {
  copyFileSync(
    join(nm, "@fontsource-variable/inter/files", `inter-${subset}-wght-normal.woff2`),
    join(fontDir, `inter-${subset}-wght-normal.woff2`),
  );
}
copyFileSync(join(nm, "@fontsource-variable/inter/LICENSE"), join(licDir, "Inter-OFL-1.1.txt"));
// Display face: Plus Jakarta Sans (OFL-1.1). Latin + latin-ext cover ğ ş ı İ ö ü ç.
for (const subset of ["latin", "latin-ext"]) {
  copyFileSync(
    join(nm, "@fontsource-variable/plus-jakarta-sans/files", `plus-jakarta-sans-${subset}-wght-normal.woff2`),
    join(fontDir, `plus-jakarta-sans-${subset}-wght-normal.woff2`),
  );
}
copyFileSync(join(nm, "@fontsource-variable/plus-jakarta-sans/LICENSE"), join(licDir, "PlusJakartaSans-OFL-1.1.txt"));
copyFileSync(join(nm, "lucide-static/LICENSE"), join(licDir, "Lucide-ISC.txt"));

// Icons: remove stale files, then copy the listed ones with the build comment and class stripped.
for (const f of readdirSync(iconDir)) if (f.endsWith(".svg")) unlinkSync(join(iconDir, f));
const names = readFileSync(join(here, "icons.txt"), "utf8").split(/\r?\n/).map((s) => s.trim()).filter(Boolean);
for (const name of names) {
  const src = join(nm, "lucide-static/icons", `${name}.svg`);
  if (!existsSync(src)) throw new Error(`Unknown Lucide icon: ${name}`);
  const svg = readFileSync(src, "utf8")
    .replace(/<!--[\s\S]*?-->\s*/g, "")
    .replace(/\s+class="[^"]*"/, "");
  writeFileSync(join(iconDir, `${name}.svg`), svg);
}
console.log(`fonts: 4, icons: ${names.length}`);

// Flags for the language picker (flag-icons, MIT), keyed by our language code.
const FLAGS = { tr: "tr", en: "gb", de: "de", es: "es", fr: "fr", pt: "br", it: "it", ru: "ru", uk: "ua", pl: "pl", nl: "nl", ja: "jp", ko: "kr", zh: "cn", id: "id" };
const flagDir = join(root, "assets", "flags");
mkdirSync(flagDir, { recursive: true });
for (const [lang, country] of Object.entries(FLAGS)) {
  copyFileSync(join(nm, "flag-icons/flags/4x3", `${country}.svg`), join(flagDir, `${lang}.svg`));
}
copyFileSync(join(nm, "flag-icons/LICENSE"), join(licDir, "flag-icons-MIT.txt"));
console.log(`flags: ${Object.keys(FLAGS).length}`);

// fonts.css: @font-face with the WOFF2 inlined as data URIs so no request is ever made.
const ranges = {
  latin:
    "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD",
  "latin-ext":
    "U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF",
};
let css = "/* Generated by tools/extract-assets.mjs. Inter Variable (OFL-1.1, see licenses/Inter-OFL-1.1.txt). */\n";
for (const subset of ["latin-ext", "latin"]) {
  const b64 = readFileSync(join(fontDir, `inter-${subset}-wght-normal.woff2`)).toString("base64");
  css += `@font-face{font-family:"Inter Variable";font-style:normal;font-display:swap;font-weight:100 900;src:url(data:font/woff2;base64,${b64}) format("woff2-variations");unicode-range:${ranges[subset]}}\n`;
}
css += "/* Plus Jakarta Sans Variable (OFL-1.1, see licenses/PlusJakartaSans-OFL-1.1.txt). */\n";
for (const subset of ["latin-ext", "latin"]) {
  const b64 = readFileSync(join(fontDir, `plus-jakarta-sans-${subset}-wght-normal.woff2`)).toString("base64");
  css += `@font-face{font-family:"Plus Jakarta Sans Variable";font-style:normal;font-display:swap;font-weight:200 800;src:url(data:font/woff2;base64,${b64}) format("woff2-variations");unicode-range:${ranges[subset]}}\n`;
}
writeFileSync(join(root, "assets", "fonts.css"), css);
